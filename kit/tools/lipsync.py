"""v5 lip-sync: words.json -> per-frame mouth shapes.   python3 lipsync.py work/words.json web/mouth.js [--fps 30] [--total N]
Writes `export const MOUTH = "..."` (one char per frame): '.' silence/none, 'c' closed, 'o' small round (o,u), 'O' open (a), 'g' wide (e,i).
Heuristic for Indonesian (and most Latin-script text): each vowel group is a syllable; it is held open for ~65 % of its slot, then closes, so the
jaw visibly moves. b/m/p at a word start close the mouth for 2 frames. Shapes change at most every 2 frames (cheaper card redraws, less flicker).
In story.js: import { MOUTH } from './mouth.js'; then pass { mouth: lipAt(MOUTH, f, a, b) } to the actor who speaks in frames a..b."""
import sys, json, re, argparse
ap = argparse.ArgumentParser(); ap.add_argument("words"); ap.add_argument("out"); ap.add_argument("--fps", type=float, default=30); ap.add_argument("--total", type=int, default=0)
A = ap.parse_args()
W = json.load(open(A.words))
N = A.total or int(max(w["e"] for w in W) * A.fps) + 20
M = ["."] * N
SH = {"a": "O", "e": "g", "i": "g", "o": "o", "u": "o"}
for w in W:
    t = re.sub(r"[^a-z]", "", w["w"].lower()) or "a"
    groups = [(m.start(), m.group()) for m in re.finditer(r"[aeiou]+", t)]
    f0, f1 = int(round(w["s"] * A.fps)), max(int(round(w["e"] * A.fps)), int(round(w["s"] * A.fps)) + 2)
    if not groups:
        for f in range(f0, min(f1, N)): M[f] = "c"
        continue
    slot = (f1 - f0) / len(groups)
    for k, (pos, v) in enumerate(groups):
        a = f0 + k * slot; o_end = a + slot * 0.65
        shape = SH[v[0]] if len(v) == 1 else SH[v[-1]] if v[-1] in "ou" else SH[v[0]]
        for f in range(int(round(a)), min(int(round(f0 + (k + 1) * slot)), N)): M[f] = shape if f < o_end else "c"
    if t[0] in "bmp":
        for f in range(f0, min(f0 + 2, N)): M[f] = "c"
# stabilise: hold each change for >= 2 frames; closed gaps between words stay closed
out = list(M); last = out[0]; hold = 0
for i in range(1, N):
    if out[i] != last and hold < 2: out[i] = last; hold += 1
    else:
        if out[i] != last: hold = 0
        else: hold += 1
        last = out[i]
open(A.out, "w").write('// generated by tools/lipsync.py from ' + A.words + '\nexport const MOUTH = "' + "".join(out) + '";\n')
speak = sum(1 for c in out if c != "."); print(f"lip-sync: {N} frames, {speak} speaking frames -> {A.out}")
